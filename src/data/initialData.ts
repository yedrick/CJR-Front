const slug = (s: string) =>
  normalizeText(s)
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '');

const INITIAL_CITIES: City[] = [];
const INITIAL_SUBDIRECTIVAS: Subdirectiva[] = [];
const INITIAL_REGIONALES: RegionalItem[] = [];

Object.entries(LOCATION_TREE).forEach(([cityName, subs]) => {
  const cityId = `city-${slug(cityName)}`;
  INITIAL_CITIES.push({ id: cityId, name: cityName });
  Object.entries(subs).forEach(([subName, regionals]) => {
    const subId = `sub-${slug(subName)}`;
    INITIAL_SUBDIRECTIVAS.push({ id: subId, name: subName, cityId });
    regionals.forEach((reg) => {
      INITIAL_REGIONALES.push({ id: `reg-${slug(reg)}`, name: reg, subdirectivaId: subId });
    });
  });
});

